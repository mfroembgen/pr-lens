import { afterAll, describe, expect, it } from "bun:test";
import { createServer, type Server } from "node:http";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { z } from "zod";
import { GraphDoc } from "@coldtea/pr-lens-schema";
import { createCanvasServer } from "../src/server.js";
import { hashToken, mintToken, openStore } from "../src/store.js";
import { startSignIn, pollSignIn, checkSignIn, whoAmI, endSession } from "../../cli/dist/account.js";
const publisher = "a".repeat(64);
const directories: string[] = [];
const servers: Server[] = [];
const listen = async (server: Server) => {
  servers.push(server);
  await new Promise<void>((resolve, reject) => { server.once("error", reject); server.listen(0, "127.0.0.1", resolve); });
  const address = server.address();
  if (address === null || typeof address === "string") throw new Error("No address");
  return `http://127.0.0.1:${address.port}`;
};
const close = async (server: Server) => { server.closeIdleConnections(); await new Promise<void>((resolve) => server.close(() => resolve())); };
const request = async (api: string, method: string, path: string, body?: unknown, headers: Record<string, string> = {}) => {
  const response = await fetch(`${api}${path}`, { method, headers: { "content-type": "application/json", ...headers }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  return { status: response.status, headers: response.headers, json: await response.json() };
};
afterAll(async () => { for (const server of servers) if (server.listening) await close(server); for (const dir of directories) await rm(dir, { recursive: true, force: true }); });

describe("the official CLI account protocol", () => {
  it("approves a device, claims its canvases, issues an opaque account token once and revokes it independently", async () => {
    const pat = "fixture-encrypted-device-test";
    const gitlab = createServer((req, res) => {
      if (req.headers["private-token"] !== pat) { res.writeHead(401); res.end("{}"); return; }
      res.setHeader("content-type", "application/json");
      res.end(JSON.stringify(req.url === "/api/v4/projects/42" ? { id: 42, path_with_namespace: "example/project", web_url: "https://gitlab.example.com/example/project", permissions: { project_access: { access_level: 30 }, group_access: null } } : { id: 7, name: "Example User", username: "example" }));
    });
    const gitlabOrigin = await listen(gitlab);
    const dir = await mkdtemp(join(tmpdir(), "canvas-device-")); directories.push(dir);
    let server = await createCanvasServer({ dir, publishToken: publisher, gitlabOrigin });
    let api = await listen(server);
    const signed = await request(api, "POST", "/api/auth/login", { token: pat }, { origin: api });
    const cookie = signed.headers.get("set-cookie")?.split(";")[0];
    if (cookie === undefined) throw new Error("No cookie");
    const install = `prl_i_${mintToken()}`;
    const canvasId = mintToken();
    const source = GraphDoc.parse(JSON.parse(await readFile(new URL("../../schema/examples/minimal.graph.json", import.meta.url), "utf8")));
    const document = { ...source, provenance: { ...source.provenance, repo: { owner: "example", name: "project", host: new URL(gitlabOrigin).host } } };
    const canvas = { id: canvasId, tokenHash: hashToken(mintToken()), rev: 1, document, createdAt: new Date().toISOString(), installHash: hashToken(install), provenance: { projectId: "42" } };
    const db = await openStore(dir);
    db.write(canvas); db.saveRevision(canvas);
    db.close();
    const started = await startSignIn(api, install, "pr-lens-cli", "Example laptop");
    expect(started).toMatchObject({ expiresInSeconds: 600, intervalSeconds: 5 });
    expect((await pollSignIn(api, started.deviceCode)).type).toBe("pending");
    expect((await pollSignIn(api, started.deviceCode)).type).toBe("slow_down");
    expect((await request(api, "GET", `/api/device?user_code=${started.userCode}`, undefined, { cookie })).json).toMatchObject({ user_code: started.userCode, status: "pending", name: "Example laptop" });
    expect((await request(api, "POST", "/api/device/approve", { user_code: started.userCode }, { cookie, origin: "https://attacker.example" })).status).toBe(403);
    expect((await request(api, "POST", "/api/device/approve", { user_code: started.userCode }, { cookie, origin: api })).json).toEqual({ ok: true, claimed: 1 });
    await close(server);
    server = await createCanvasServer({ dir, publishToken: publisher, gitlabOrigin });
    api = await listen(server);
    const saved = await openStore(dir);
    const device = saved.device(hashToken(started.deviceCode));
    if (device === undefined) throw new Error("Missing grant");
    saved.saveDevice({ ...device, nextPollAt: 0 }); saved.close();
    const grant = await pollSignIn(api, started.deviceCode);
    expect(grant.type).toBe("token");
    if (grant.type !== "token") throw new Error("No token");
    expect(grant.token).toMatch(/^prl_u_[A-Za-z0-9_-]{22}$/);
    expect(grant.token).not.toBe(pat);
    expect(grant.claimed).toBe(1);
    expect((await pollSignIn(api, started.deviceCode)).type).toBe("expired");
    expect(await whoAmI(api, grant.token)).toBe("example@127.0.0.1");
    expect(await checkSignIn(api, grant.token, install)).toEqual({ type: "live", machine: "linked" });
    const stored = await openStore(dir);
    expect(stored.read(canvasId)?.owner).toBe(`gitlab:${gitlabOrigin}:7`);
    const boundSession = stored.authSession(hashToken(grant.token));
    expect(boundSession?.installHash).toBe(hashToken(install));
    if (boundSession === undefined) throw new Error("No persisted account session");
    const legacyToken = `prl_u_${mintToken()}`;
    const { installHash: _installHash, ...legacySession } = boundSession;
    stored.saveAuthSession({ ...legacySession, id: hashToken(legacyToken) });
    expect(await whoAmI(api, legacyToken)).toBeUndefined();
    const machine = stored.machine(hashToken(install));
    if (machine === undefined) throw new Error("No linked machine");
    stored.saveMachine({ ...machine, revoked: true });
    expect(await whoAmI(api, grant.token)).toBeUndefined();
    expect(stored.authSession(hashToken(grant.token))).toBeDefined();
    stored.saveMachine({ ...machine, revoked: false });
    expect(await whoAmI(api, grant.token)).toBe("example@127.0.0.1");
    stored.close();
    expect((await request(api, "GET", `/api/canvas/${canvasId}/page`, undefined, { authorization: `Bearer ${grant.token}` })).status).toBe(200);
    const second = await startSignIn(api, install, "pr-lens-cli", "Example laptop");
    await request(api, "POST", "/api/device/approve", { user_code: second.userCode }, { cookie, origin: api });
    const secondGrant = await pollSignIn(api, second.deviceCode);
    if (secondGrant.type !== "token") throw new Error("No second token");
    const outstanding = await startSignIn(api, install, "pr-lens-cli", "Example laptop");
    await request(api, "POST", "/api/device/approve", { user_code: outstanding.userCode }, { cookie, origin: api });
    expect((await request(api, "DELETE", `/api/machines/${hashToken(install)}`, undefined, { authorization: `Bearer ${grant.token}` })).status).toBe(200);
    expect(await checkSignIn(api, grant.token, install)).toEqual({ type: "rejected" });
    expect(await whoAmI(api, secondGrant.token)).toBeUndefined();
    expect((await request(api, "GET", "/api/account", undefined, { authorization: `Bearer ${grant.token}` })).status).toBe(401);
    expect((await request(api, "GET", `/api/canvas/${canvasId}/page`, undefined, { authorization: `Bearer ${grant.token}` })).status).toBe(401);
    expect((await request(api, "PUT", `/api/canvas/${canvasId}`, document, { authorization: `Bearer ${grant.token}`, "if-match": "1", "x-pr-lens-publish-token": publisher })).status).toBe(401);
    expect((await pollSignIn(api, outstanding.deviceCode)).type).toBe("denied");
    expect(await endSession(api, grant.token)).toBe("already");
    expect((await request(api, "GET", "/api/auth/me", undefined, { cookie })).status).toBe(200);
    const afterRevocation = await openStore(dir);
    expect(afterRevocation.authSession(hashToken(grant.token))).toBeUndefined();
    expect(afterRevocation.authSession(hashToken(secondGrant.token))).toBeUndefined();
    afterRevocation.close();
    const fresh = await startSignIn(api, install, "pr-lens-cli", "Example laptop");
    expect((await request(api, "POST", "/api/device/approve", { user_code: fresh.userCode }, { cookie, origin: api })).status).toBe(200);
    const relinked = await pollSignIn(api, fresh.deviceCode);
    if (relinked.type !== "token") throw new Error("Relink did not issue a token");
    expect(await whoAmI(api, relinked.token)).toBe("example@127.0.0.1");
    expect(await whoAmI(api, grant.token)).toBeUndefined();
    expect((await pollSignIn(api, outstanding.deviceCode)).type).toBe("denied");
    expect(await endSession(api, relinked.token)).toBe("ended");
    await close(server);
    const bytes = await readFile(join(dir, "canvas.sqlite"));
    expect(bytes.includes(Buffer.from(pat))).toBe(false);
    expect(bytes.includes(Buffer.from(grant.token))).toBe(false);
    expect(bytes.includes(Buffer.from(started.deviceCode))).toBe(false);
  });

  it("denies and expires grants and bounds issuance per address", async () => {
    const gitlab = createServer((_req, res) => { res.setHeader("content-type", "application/json"); res.end(JSON.stringify({ id: 1, name: "Example", username: "example" })); });
    const gitlabOrigin = await listen(gitlab);
    const dir = await mkdtemp(join(tmpdir(), "canvas-device-limits-")); directories.push(dir);
    const server = await createCanvasServer({ dir, publishToken: publisher, gitlabOrigin });
    const api = await listen(server);
    const login = await request(api, "POST", "/api/auth/login", { token: "test-token" }, { origin: api });
    const cookie = login.headers.get("set-cookie")?.split(";")[0] ?? "";
    const started = await startSignIn(api, `prl_i_${mintToken()}`, "cli", "Laptop");
    expect((await request(api, "POST", "/api/device/deny", { user_code: started.userCode }, { cookie, origin: api })).status).toBe(200);
    expect((await pollSignIn(api, started.deviceCode)).type).toBe("denied");
    const next = await startSignIn(api, `prl_i_${mintToken()}`, "cli", "Laptop");
    const db = await openStore(dir);
    const saved = db.device(hashToken(next.deviceCode));
    if (saved === undefined) throw new Error("Missing device");
    db.saveDevice({ ...saved, expiresAt: Date.now() - 1 }); db.close();
    expect((await pollSignIn(api, next.deviceCode)).type).toBe("expired");
    for (let count = 2; count < 20; count += 1) expect((await request(api, "POST", "/api/device/code", { install_id: `prl_i_${mintToken()}`, client: "cli", name: "Laptop" })).status).toBe(200);
    expect((await request(api, "POST", "/api/device/code", { install_id: `prl_i_${mintToken()}`, client: "cli", name: "Laptop" })).status).toBe(429);
  });
});

describe("legacy storage", () => {
  it("imports JSON canvases once and never resurrects a deletion", async () => {
    const dir = await mkdtemp(join(tmpdir(), "canvas-legacy-")); directories.push(dir);
    const id = mintToken();
    const document = JSON.parse(await readFile(new URL("../../schema/examples/minimal.graph.json", import.meta.url), "utf8"));
    await writeFile(join(dir, `${id}.json`), JSON.stringify({ id, tokenHash: hashToken(mintToken()), rev: 3, document, createdAt: new Date().toISOString() }));
    const first = await openStore(dir);
    expect(first.read(id)?.document).toEqual(document);
    expect(first.revision(id, 3)?.document).toEqual(document);
    first.remove(id); first.close();
    const restarted = await openStore(dir);
    expect(restarted.read(id)).toBeUndefined(); restarted.close();
  });
});
